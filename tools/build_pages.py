#!/usr/bin/env python3
"""Write the book's question pages and the answer tables from the exams and the explanations.

Inputs:  exams/source/*.md (the three versions), content/key-version-A.json,
         content/explanations/ANN.json (the explanations, one file per Version A question)
Outputs: version-a-explained.qmd, answers-all-versions.qmd (do not edit these by hand)

Run from the repository folder:  python3 tools/build_pages.py   (then: quarto render)
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from exam import KEYS, QUESTIONS, SAME, check, split_label  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
EXPL = ROOT / "content" / "explanations"
PAGE = "version-a-explained"   # all 45 questions are on this one page
NOTE = "<!-- Generated by tools/build_pages.py from the exams and content/explanations/. Do not edit by hand. -->\n"


def page_name(q):
    return PAGE


def load(q):
    f = EXPL / f"A{q:02d}.json"
    return json.loads(f.read_text()) if f.exists() else None


def other_versions(q):
    b, c = SAME[q]["B"], SAME[q]["C"]
    if q >= 44:
        return (f"In the other versions, this was question {b} in Version B and question {c} in Version C. "
                f"The items and meanings are in a different order there, so the letters are different.")
    return (f"In the other versions, this was question {b} in Version B (correct answer: {KEYS['B'][b]}) and "
            f"question {c} in Version C (correct answer: {KEYS['C'][c]}). The choices are in a different order in "
            f"each version.")


def mc_block(q, Q, ex):
    key = KEYS["A"][q]
    out = []
    for k, text in Q["options_md"].items():
        why = (ex or {}).get("choices", {}).get(k, "")
        cls = ".choice .correct" if k == key else ".choice"
        mark = " [(correct answer)]{.correct-tag}" if k == key else ""
        out.append(f"::: {{{cls}}}")
        out.append(f"[{k}.]{{.letter}} {text}{mark}")
        if why:
            out.append("")
            out.append("::: {.why}")
            out.append(why)
            out.append(":::")
        out.append(":::")
        out.append("")
    return out


def matching_block(q, Q, ex):
    items = [split_label(i) for i, _ in Q["table"] if i]
    choices = dict(split_label(c) for _, c in Q["table"])
    want = {n: l for n, l in re.findall(r"(\d)([A-G])", KEYS["A"][q])}
    out = ["| Item | Correct match | Meaning |", "|------|:---:|------|"]
    for n, name in items:
        out.append(f"| {n}. {name} | **{want[n]}** | {choices[want[n]]} |")
    unused = [l for l in choices if l not in want.values()]
    for l in unused:
        out.append(f"| (not used) | {l} | {choices[l]} |")
    out.append("")
    if ex:
        for n, name in items:
            why = ex.get("items", {}).get(n, "")
            why = re.sub(r"^[^.]*?\s*(->|→)\s*[A-G]\.\s*", "", why)   # drop a leading "Jailbreak -> A."
            if why:
                out += [f"::: {{.choice .correct}}", f"[{n}.]{{.letter}} {name} → **{want[n]}**", "",
                        "::: {.why}", why, ":::", ":::", ""]
        for l in unused:
            why = ex.get("unused", {}).get(l, "")
            if why:
                out += ["::: {.choice}", f"[{l}.]{{.letter}} {choices[l]} [(not used)]{{.unused-tag}}", "",
                        "::: {.why}", why, ":::", ":::", ""]
    return out


def question_section(q):
    Q = QUESTIONS["A"][q]
    ex = load(q)
    title = (ex or {}).get("title", "")
    out = [f"## Question {q}{': ' + title if title else ''} {{#q{q}}}", ""]
    if q >= 44:
        out += ["::: {.callout-note appearance=\"minimal\"}",
                "Matching was not graded on this exam: everyone was told to skip it. It is explained here so that "
                "you can learn the material.", ":::", ""]
    out += ["::: {.stem}", Q["stem_md"], ":::", ""]
    out += matching_block(q, Q, ex) if Q["table"] else mc_block(q, Q, ex)
    out += [f"[{other_versions(q)}]{{.other-versions}}", ""]
    if ex and ex.get("tutorial"):
        out += ["### Background {.unnumbered .unlisted}", "", ex["tutorial"], ""]
    if ex and ex.get("read_more"):
        out += ["**Read more in the course book:**", ""]
        out += [f"- [{r['text']}]({r['url']})" for r in ex["read_more"]]
        out.append("")
    if not ex:
        out += ["*(The explanation for this question is not written yet.)*", ""]
    return out


def write_pages():
    out = [NOTE, "# Version A, explained {.unnumbered}", ""]
    out += ["These are all 45 questions of Version A. If you had Version B or C, find your question number in "
            "[Answers for all three versions](answers-all-versions.qmd). The list of questions on the right side "
            "of the page links to each question.", ""]
    for q in range(1, 46):
        out += question_section(q)
    (ROOT / f"{PAGE}.qmd").write_text("\n".join(out))


def short(s, n=70):
    return s if len(s) <= n else s[: n - 1].rsplit(" ", 1)[0] + " …"


def write_answers():
    out = [NOTE, "# Answers for all three versions", "",
           "Every version has the same 45 questions and the same answer choices. Only the order of the questions, "
           "and the order of the choices in each question, is different.", "",
           "Find your version by question 1 of your test paper:", ""]
    for v in "ABC":
        out.append(f"- **Version {v}**: question 1 starts \"{short(QUESTIONS[v][1]['stem'], 80)}\"")
    out += ["", "Each row is one question. The link goes to its explanation (written for Version A: the letters "
            "of the choices may be different in your version, but the text of the choices is the same).", "",
            "| Version A | Version B | Version C | Question | Explanation |",
            "|:---|:---|:---|------|------|"]
    for q in range(1, 46):
        b, c = SAME[q]["B"], SAME[q]["C"]
        def cell(v, n):
            return f"{n}: **{KEYS[v][n]}**"
        out.append(f"| {cell('A', q)} | {cell('B', b)} | {cell('C', c)} | {short(QUESTIONS['A'][q]['stem'])} | "
                   f"[Question {q}]({page_name(q)}.qmd#q{q}) |")
    out += ["", "## Answer key by version", "",
            "The same answers, listed by question number in each version.", "", "::: {.panel-tabset}", ""]
    for v in "ABC":
        out += [f"### Version {v}", "", "| Question | Answer | Explanation |", "|---:|:---|---|"]
        inv = {SAME[qa][v]: qa for qa in SAME}
        for n in range(1, 46):
            qa = inv[n]
            out.append(f"| {n} | **{KEYS[v][n]}** | [Version A question {qa}]({page_name(qa)}.qmd#q{qa}) |")
        out.append("")
    out += [":::", ""]
    (ROOT / "answers-all-versions.qmd").write_text("\n".join(out))


if __name__ == "__main__":
    problems = check()
    if problems:
        sys.exit("The versions do not match:\n" + "\n".join(problems))
    write_pages()
    write_answers()
    missing = [q for q in range(1, 46) if load(q) is None]
    print("wrote the question pages and answers-all-versions.qmd;",
          f"explanations missing for: {missing}" if missing else "all 45 explanations present")
